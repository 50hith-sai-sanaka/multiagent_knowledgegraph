"""
AST-Level Read-Only Cypher Validator ("Schema Shield")
File: src/analyst/ast_validator.py

Validates LLM-generated Cypher queries to ensure:
  1. Only read operations (MATCH, WHERE, WITH, RETURN, ORDER BY, LIMIT, OPTIONAL MATCH).
  2. No mutation tokens (CREATE, MERGE, DELETE, DETACH, SET, REMOVE, DROP, CALL, LOAD CSV).
  3. All node labels and relationship types are within the allowed ontology.
  4. A safety LIMIT cap is enforced if the LLM omits one.
"""

from __future__ import annotations

import re
import logging
from typing import Any

logger = logging.getLogger(__name__)

# ──────────────────────────────────────────────────────────────────────────────
# Allowed and Disallowed Token Sets
# ──────────────────────────────────────────────────────────────────────────────

ALLOWED_NODE_LABELS = frozenset({
    "IP", "Domain", "URL", "Malware", "FileHash", "ThreatActor",
    "Campaign", "AttackTechnique",
    # Cold provenance labels
    "Claim", "Evidence", "Conflict", "Decision", "Principal",
})

ALLOWED_RELATIONSHIP_TYPES = frozenset({
    # Hot domain edges
    "USES_C2", "DISTRIBUTED_VIA", "HOSTED_ON", "ATTRIBUTED_TO",
    "PART_OF", "EXPLOITS", "TARGETS", "MITIGATED_BY", "RESOLVES_TO",
    "HAS_SAMPLE",
    # Cold provenance edges
    "ASSERTED", "ASSERTS", "GROUNDED_IN", "SUPPORTED_BY",
    "INVOLVED_IN", "HAS_DECISION", "RESOLVED_BY", "CONTESTED",
    "CORROBORATES", "DISPUTES", "PROTECTS",
})

# Tokens that indicate a mutation — case-insensitive word boundary match
_MUTATION_TOKENS = frozenset({
    "CREATE", "MERGE", "DELETE", "DETACH", "SET", "REMOVE",
    "DROP", "CALL", "LOAD",
})

_MUTATION_PATTERN = re.compile(
    r"\b(" + "|".join(_MUTATION_TOKENS) + r")\b",
    re.IGNORECASE,
)

_LIMIT_PATTERN = re.compile(r"\bLIMIT\b", re.IGNORECASE)

# Extract `:Label` from node patterns `(n:Label)` — NOT inside brackets `[:REL]`
_LABEL_PATTERN = re.compile(r"\([\w]*:([A-Z][A-Za-z0-9_]+)")
_REL_TYPE_PATTERN = re.compile(r"\[:?([A-Z_][A-Z0-9_]*(?:\|[A-Z_][A-Z0-9_]*)*)\]")

MAX_SAFETY_LIMIT = 50


class CypherValidationError(Exception):
    """Raised when a generated Cypher query fails safety validation."""

    def __init__(self, message: str, violations: list[str] | None = None):
        super().__init__(message)
        self.violations = violations or []


class CypherValidator:
    """Validates Cypher queries generated by the Text-to-Cypher engine."""

    def __init__(
        self,
        allowed_labels: frozenset[str] | None = None,
        allowed_rels: frozenset[str] | None = None,
        max_limit: int = MAX_SAFETY_LIMIT,
    ):
        self._allowed_labels = allowed_labels or ALLOWED_NODE_LABELS
        self._allowed_rels = allowed_rels or ALLOWED_RELATIONSHIP_TYPES
        self._max_limit = max_limit

    def validate(self, cypher: str) -> str:
        """
        Validate and optionally sanitize a Cypher query.

        Returns the (possibly amended) query string.
        Raises CypherValidationError if the query is unsafe.
        """
        violations: list[str] = []

        # 1. Check for mutation tokens
        mutations = _MUTATION_PATTERN.findall(cypher)
        if mutations:
            violations.append(
                f"Mutation operations detected: {', '.join(set(m.upper() for m in mutations))}. "
                f"Only read-only queries (MATCH/RETURN) are allowed."
            )

        # 2. Check node labels against ontology
        labels_found = set(_LABEL_PATTERN.findall(cypher))
        # Filter out common Cypher aliases and property names
        _ignore = {"id", "value", "name", "status", "accepted", "sha256", "md5", "sha1"}
        labels_to_check = {
            label for label in labels_found
            if label[0].isupper() and label.lower() not in _ignore
        }
        unknown_labels = labels_to_check - self._allowed_labels
        if unknown_labels:
            violations.append(
                f"Unknown node labels: {', '.join(sorted(unknown_labels))}. "
                f"Allowed labels: {', '.join(sorted(self._allowed_labels))}."
            )

        # 3. Check relationship types against ontology
        rel_matches = _REL_TYPE_PATTERN.findall(cypher)
        for match in rel_matches:
            for rel in match.split("|"):
                rel = rel.strip()
                if rel and rel not in self._allowed_rels:
                    # Check if it looks like a relationship type (all caps with underscores)
                    if re.fullmatch(r"[A-Z_][A-Z0-9_]*", rel):
                        violations.append(
                            f"Unknown relationship type: {rel}. "
                            f"Allowed types: {', '.join(sorted(self._allowed_rels))}."
                        )

        if violations:
            raise CypherValidationError(
                f"Cypher query failed {len(violations)} safety check(s).",
                violations=violations,
            )

        # 4. Enforce safety LIMIT cap
        sanitized = cypher.rstrip().rstrip(";")
        if not _LIMIT_PATTERN.search(sanitized):
            sanitized = f"{sanitized} LIMIT {self._max_limit}"
            logger.info("Auto-appended LIMIT %d to Cypher query.", self._max_limit)

        return sanitized

    def is_safe(self, cypher: str) -> bool:
        """Return True if the query passes all checks, False otherwise."""
        try:
            self.validate(cypher)
            return True
        except CypherValidationError:
            return False
