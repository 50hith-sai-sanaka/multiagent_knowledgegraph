# src/agents/state.py
"""AgentState TypedDict — Stories 010 & 011.

This is the shared state dict that flows through all nodes of the
LangGraph state machine. Each node receives the full state and returns a
partial dict (only the fields it changed). LangGraph merges the updates
automatically.

Story 011 added ``llm_summary`` and ``llm_extra_props`` to carry the
output of the LLM enrichment node.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional
from typing_extensions import TypedDict

from src.schemas.models import CoordinationResult, GraphOperation


class AgentState(TypedDict, total=False):
    """Shared state for the agent workflow.

    All fields are optional (total=False) because each node only sets
    the fields it is responsible for. Fields not yet set return None
    when accessed with ``state.get("field_name")``.

    Fields
    ------
    principal_id:
        Which agent this is. One of:
        "Principal-ThreatFox", "Principal-URLhaus",
        "Principal-MalwareBazaar", "Principal-OTX"
    ioc_value:
        The IOC string being processed (e.g. "https://bok.6666k.org").
    protocol:
        Coordination protocol: "adhoc", "mpac", "ablation_no_a2a",
        "ablation_no_locks", or "ablation_timestamp".
    neo4j_client:
        The connected Neo4j client instance.
    lock_manager:
        Optional application-scoped semantic lock manager shared by requests.
    evidence:
        List of matching record dicts returned by the MCP tool.
        Empty list if nothing was found.
    claim_malware_family:
        The ``malware_family`` string from the first evidence record.
        None if evidence is empty or has no ``malware_family``.
    node_label:
        The Tier 1 Neo4j node label derived from the IOC type
        (e.g. "IP", "URL", "FileHash"). Defaults to "Malware".
    claim:
        The ``GraphOperation`` object built in ``extract_claim``.
        None if evidence was empty or ontology rejected the label.
    peer_votes:
        List of ``A2AResponse`` objects from the peer hub.
    consensus_score:
        Float in [0.0, 1.0] — aggregate peer consensus.
    result:
        The ``CoordinationResult`` returned by the coordinator.
    error:
        Error message string if a step failed. None normally.
    llm_summary:
        Natural-language 2-sentence summary generated by the LLM enrichment
        node. Empty string when LLM is unavailable (graceful fallback).
    llm_extra_props:
        Extra Neo4j node properties proposed by the LLM (e.g. tactics,
        severity, CVE IDs). Merged into ``GraphOperation.properties`` before
        the coordinator is called. Empty dict on fallback.
    """

    principal_id: str
    ioc_value: str
    protocol: str
    neo4j_client: Any
    lock_manager: Any
    evidence: List[Dict[str, Any]]
    claim_malware_family: Optional[str]
    node_label: str
    claim: Optional[GraphOperation]
    peer_votes: List[Any]
    consensus_score: float
    result: Optional[CoordinationResult]
    error: Optional[str]
    # Story 011 – LLM enrichment output
    llm_summary: Optional[str]
    llm_extra_props: Optional[Dict[str, Any]]
